import numpy as np


ROLE = (
    "Tu es l'assistant virtuel de l'Hôtel Le Belvédère, au bord du lac d'Annecy.\n"
    "Voici la documentation officielle de l'hôtel :"
)

CONSIGNE = (
    "Réponds en une ou deux phrases, uniquement à partir des informations "
    "de la documentation ci-dessus. Si l'information ne s'y trouve pas, réponds exactement : "
    '"Je ne sais pas, je vous invite à contacter la réception."'
)


# Principe du RAG. 
# Lorsqu'une question est donnée, trois opérations ont lieu :
# (1) encoder la question en vecteur
# (2) calculer sa similarité avec chacune des rubriques liées aux donnés de l'entreprise
# (3) garder les `top_k` rubriques les plus proches.

def _search_top_indices(question, chunks_embedded, embedding_model, top_k=2):
    """
    Ressort le top_k des vecteurs de chunks des documents les + proches
    Arguments:
    question -- la question du client sous forme de string
    chunks_embedded -- chunks vectorisés à partir des textes de l'entreprise
    embedding_model -- modèle d'embedding qui a permi de vectoriser les chunks
    pages -- 
    top_k -- nombre de chunks à retourner (ici textes des pages pdf)
    Returns:
    results -- le top_k des indices des chunks les + proches
    """
    # (1) on encode la question en vecteur (avec le même modèle que les chunks), normalisé (comme pour les chunks)
    question_embedded = embedding_model.encode(question, normalize_embeddings=True) 

    # (2) ou nb.dot(chunk_embeddings, question_embedding)  # on calcule la similarité cosinus entre la question et chaque chunck        
    similarities = chunks_embedded @ question_embedded  # retourne des valeurs entre -1 et 1

    # (3) similarities est trié par ordre décroissant, et on prend les indices correspondant aux top-k premières valeurs, 
    # ie : les indices des rubriques / des chunks les plus pertinentes pour la question
    top_indices = np.argsort(similarities)[::-1][:top_k]  
    return top_indices, similarities[top_indices]


def _search(pages, top_indices, similarities):
    results = pages.iloc[top_indices].copy()   # on récupère uniquement les top-k lignes du DataFrame pages correspondant aux indices des rubriques les plus pertinentes
    results["score"] = similarities    #on ajoute une colonne score qui contient la similarité des top-k rubriques les plus pertinentes avec la question
    return results


def _build_prompt(context, question):
    """
    Build the prompt sent to the LLM from a context and a question.

    Arguments:
    context -- the documentation the answer must be based on, as a string
    question -- the client's question, as a string

    Returns:
    prompt -- the full prompt, as a string
    """
    prompt = f"{ROLE}\n\n{context}\n\nQuestion d'un client : {question}\n{CONSIGNE}"
    return prompt


def _ask_llm(prompt, generator):
    """
    Send one message to the LLM and return its answer.

    Arguments:
    prompt -- the message to send, as a string

    Returns:
    answer -- the text generated by the model
    """
    conversation = generator([{"role": "user", "content": prompt}], max_new_tokens=80, do_sample=False)
    answer = conversation[0]["generated_text"][-1]["content"]
    return answer




def answer_question(question, pages, chunks_embedded, embedding_model, generator, top_k=2):
    """
    Answer a question using the full RAG pipeline.

    Arguments:
    question -- 
    top_k -- number of pages to retrieve

    Returns:
    answer -- the generated answer, as a string
    retrieved -- the DataFrame of pages used as context
    """
    top_indices, similarities = _search_top_indices(question, chunks_embedded, embedding_model, top_k)
    retrieved = _search(pages, top_indices, similarities)  # on récupère les top-k rubriques les plus pertinentes pour la question
    context = retrieved
    print(f"contexte {context}")
    prompt = _build_prompt(context, question)  # on construit le prompt à partir du contexte et de la question
    answer = _ask_llm(prompt, generator)  # on envoie le prompt au LLM et on récupère sa réponse
    return answer, retrieved
